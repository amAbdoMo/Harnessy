/**
 * Render one provider's brand glyph at the shared badge size. Monochrome marks
 * follow the badge ink through `currentColor`; providers whose identity is a
 * fixed color keep it.
 * @param props - provider whose mark renders.
 * @returns the provider's brand glyph.
 */
export function ProviderMark({ provider }: {
  readonly provider: AccountProviderId
}) {
  switch (provider) {
    case 'openai-codex': return <CodexMark />
    case 'zai': return <GlmMark />
    case 'kimi-coding': return <KimiMark />
    case 'opencode': return <OpencodeMark />
    case 'anthropic': return <ClaudeMark />
    default: return assertNever(provider, 'AccountProviderId')
  }
}
